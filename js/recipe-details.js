/* Подключаем подробные инструкции к блюдам. */
(function applyRecipeDetails() {
  if (typeof DISHES === 'undefined') return;
  DISHES.forEach(function (dish) {
    const detail = RECIPE_DETAILS[dish.id];
    if (!detail) return;
    if (detail.prep) dish.prep = detail.prep;
    if (detail.steps && detail.steps.length) dish.steps = detail.steps;
    if (detail.doneness) dish.doneness = detail.doneness;
    if (detail.tip) dish.tip = detail.tip;
    if (detail.serve) dish.serve = detail.serve;
    if (detail.difficulty) dish.difficulty = detail.difficulty;
  });
})();
